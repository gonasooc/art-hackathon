/**
 * Refresh the three deliberately selected source fragments and the existing
 * portfolio mockup. Reads the source repository; writes only this prototype.
 *
 * node scripts/extract-portfolio.mjs [path-to-my_portfolio]
 */
import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = resolve(
  process.argv[2] || '/Users/gonasooc/Desktop/gonasoo.dev/repositories/my_portfolio',
);

const selections = [
  {
    file: 'js/main.js',
    start: "    var typed = new Typed('.typing', {",
    end: '      });',
  },
  {
    file: 'js/main.js',
    start: "    $('.tab-list li').click(function(){",
    end: '    });',
  },
  {
    file: 'css/main.css',
    start: '#main .about_wrap .about_inner .about {',
    end: '}',
  },
];

async function extract({ file, start, end }) {
  const text = await readFile(join(sourceRoot, file), 'utf8');
  const lines = text.split(/\r?\n/);
  const first = lines.findIndex((line) => line === start);
  if (first === -1) throw new Error(`Source marker missing in ${file}: ${start}`);
  const last = lines.findIndex((line, index) => index > first && line === end);
  if (last === -1 || last - first > 30) {
    throw new Error(`Source block changed in ${file}; review selection before refreshing.`);
  }
  return { file, startLine: first + 1, text: lines.slice(first, last + 1).join('\n') };
}

// Only these two source files and one existing image are read. No repository
// archive, Git history, contacts, or runtime configuration is copied.
const fragments = await Promise.all(selections.map(extract));
const originalImage = join(sourceRoot, 'images/mockup/my_mockup.png');
const imageBytes = await readFile(originalImage);
const pngSignature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
if (imageBytes.length < 24 || !imageBytes.subarray(0, 8).equals(pngSignature)) {
  throw new Error('Expected the existing portfolio mockup to be a valid PNG.');
}

const portfolio = {
  id: 'code',
  title: 'gonasooc',
  author: 'gonasooc',
  kind: 'real',
  image: './public/assets/portfolio/portfolio.png',
  sourceLabel: 'my_portfolio',
  fragments,
  provenance: '실제 포트폴리오 소스와 저장소의 기존 목업 이미지입니다. 현재 파일을 발췌했으며 Git 수정 이력은 사용하지 않았습니다. 코드 타이핑은 전시를 위한 재생 연출이며 과거 작업 기록을 복원한 것이 아닙니다.',
};

const imageDirectory = join(projectRoot, 'public/assets/portfolio');
await mkdir(imageDirectory, { recursive: true });
await mkdir(join(projectRoot, 'src'), { recursive: true });
await copyFile(originalImage, join(imageDirectory, 'portfolio.png'));
await writeFile(
  join(projectRoot, 'src/portfolio-data.js'),
  '// Generated by scripts/extract-portfolio.mjs from explicitly selected local materials.\n' +
    `export const portfolio = ${JSON.stringify(portfolio, null, 2)};\n`,
);
console.log(
  `Portfolio materials refreshed: ${fragments.length} verified source fragments; ` +
    `${imageBytes.readUInt32BE(16)} × ${imageBytes.readUInt32BE(20)} PNG.`,
);
